def layer_totals(s):
    return {"L1": sum(s[0:5]), "L2": sum(s[5:12]), "L3": sum(s[12:17]), "L4": sum(s[17:22])}

def layer_pass(t):
    return {"L1": t["L1"] >= 6.3, "L2": t["L2"] >= 10.5, "L3": t["L3"] >= 6.3, "L4": t["L4"] >= 6.3}

def main():
    for b in sorted(B.keys(), key=lambda x: int(x)):
        data = B[b]
        s = data["s"]
        ev = EVID[b]
        scores = {}
        for i, d in enumerate(DIMS):
            scores[d] = {"score": s[i], "max": MAXS[d], "evidence": ev[d]}
        t = layer_totals(s)
        lp = layer_pass(t)
        overall = all(lp.values())
        out = {
            "bundle_id": "BUNDLE_" + b,
            "evaluator_id": "C",
            "rubric_version": "v1.1",
            "scores": scores,
            "layer_totals": t,
            "layer_max": {"L1": 9, "L2": 15, "L3": 9, "L4": 9},
            "layer_pass": lp,
            "overall_pass": overall,
            "notes": data["nt"],
        }
        path = os.path.join(OUT, "BUNDLE_%s.json" % b)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=1)
        print("BUNDLE_%s L1=%d/%s L2=%d/%s L3=%d/%s L4=%d/%s OVER=%s"
              % (b, t["L1"], "P" if lp["L1"] else "F", t["L2"], "P" if lp["L2"] else "F",
                 t["L3"], "P" if lp["L3"] else "F", t["L4"], "P" if lp["L4"] else "F", overall))
    print("done: %d files" % len(B))

if __name__ == "__main__":
    main()
